"""Regenerate dataset/README.md from dataset/manifest.jsonl and inputs/faces/manifest.json.

Usage: python scripts/build_dataset_readme.py
"""
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATASET = ROOT / "dataset"

latest = {}
for line in open(DATASET / "manifest.jsonl", encoding="utf-8"):
    r = json.loads(line)
    latest[(r["generator"], r["pair_id"])] = r
by = collections.defaultdict(list)
for (g, _), r in latest.items():
    by[g].append(r)
face_sets = []  # (folder, manifest, pairs file, pair-id prefix)
for folder, pairs_file in (("faces", "pairs.json"), ("faces_p3", "pairs_p3.json")):
    mp = ROOT / "inputs" / folder / "manifest.json"
    if mp.exists():
        pairs = json.loads((ROOT / "inputs" / pairs_file).read_text(encoding="utf-8"))["pairs"]
        face_sets.append((folder, json.loads(mp.read_text(encoding="utf-8")), pairs_file, len(pairs), pairs[0]["pair_id"][0]))
faces = face_sets[0][1]

table = ["| generator | ok | status | commit | settings |", "|---|---|---|---|---|"]
total = usable = 0
for g in sorted(by):
    rs = by[g]
    ok = sum(r["status"] == "ok" for r in rs)
    total += ok
    usable += ok > 0
    status = "usable" if ok else rs[0]["status"]
    settings = {k: v for k, v in rs[0]["settings"].items() if k != "tool"}
    table.append(f"| {g} | {ok}/{len(rs)} | {status} | {(rs[0]['repo_commit'] or '')[:8]} | `{json.dumps(settings)}` |")
n_real = len({r["real_counterpart"] for r in latest.values()})

readme = f"""# Deepfake detection dataset: face swap, pass 1

Generated by the `/collect-dataset` agent. **{total} fake images** from **{usable} generators**, plus **{n_real} real counterparts**.
Every generator used the same source→target pairs (`inputs/pairs.json`), so outputs can be compared pair by pair across generators.

## Layout
```
real/<target_id>.jpg                  un-swapped target images (the "real" class; see caveat)
fake/<generator>/<pair_id>.(png|jpg)  swapped outputs
quarantine/                           generated but excluded (e.g. watermarked); do NOT train on these
sheets/<generator>.jpg                target|output contact sheets used for visual QA
manifest.jsonl                        one row per attempt: generator, repo_commit, pair, source/target ids,
                                      settings, sha256, status, diff_from_target, seconds
```

## Generators
{chr(10).join(table)}

Per-repo setup notes and fixes: `repos/<name>/_agent/report.md`. Repo-level summary: `repos/RESULTS.md`.

## Inputs (provenance)
Source: {faces['source']}. URL: {faces['source_url']}; license: {faces['license']}.

| face set | SFHQ part | faces | pairs file | pair ids | look |
|---|---|---|---|---|---|
{chr(10).join(f"| inputs/{f} | {m['part']} | {len(m['images'])} | inputs/{pf} | {pre}000–{pre}{n - 1:03d} | {'some stylised / render-like (artistic inspiration images)' if m['part'] == 1 else 'photo-like (StyleGAN2 samples)'} |" for f, m, pf, n, pre in face_sets)}

All faces are 1024×1024 JPEG, read from the HF mirror zips ({faces['mirror'].rsplit('/', 1)[0]}/) via HTTP range requests.

## Caveats
- **The "real" class is synthetic too.** Targets are SFHQ faces (StyleGAN-based), so a detector trained on this set alone can learn
  SFHQ/StyleGAN traces instead of swap artifacts. For a real-vs-fake detector, add licensed real face data
  (e.g. FaceForensics++ / DFDC originals) to the real class.
- **File format differs by generator.** Some write JPEG (FaceFusion at q100, dlib FaceSwap) and others PNG. The real images are JPEG.
  Detectors can latch onto compression differences, so normalise (e.g. re-encode everything the same way) before training.
- **Several generators share a core model.** deep-live-cam and inswapper-codeformer both use inswapper_128; ghost-unet2 and
  facefusion-ghost_1_256 are both GHOST; facefusion-simswap_* and the quarantined simswap-224 are SimSwap. Group by family when
  splitting train/test.
- **Two input styles.** Part-1 pairs (`p*`) include stylised, render-like faces; part-3 pairs (`q*`) are photo-like.
  Keep them apart (or stratify) when splitting, and prefer `q*` when the target domain is real photos.
- **Small sample.** 50 pairs per generator is still small for training. Scale up with
  `scripts/fetch_synthetic_faces.py --count 2N` + `scripts/make_pairs.py --count N`, then re-run `/collect-dataset`.
- **Licenses.** inswapper, SimSwap, BlendFace and several other models are licensed for non-commercial research only.
"""
(DATASET / "README.md").write_text(readme, encoding="utf-8")
print(f"wrote dataset/README.md: {total} fakes, {usable} generators, {n_real} real")
